import { chromium } from '../node_modules/playwright/index.mjs';
import { installDemoApi, demoInit } from './demo-api.mjs';
import fs from 'fs';
fs.rmSync('rec', { recursive: true, force: true });
const browser = await chromium.launch({ channel: 'chrome' });
const ctx = await browser.newContext({ viewport: { width: 1920, height: 1080 }, recordVideo: { dir: 'rec', size: { width: 1920, height: 1080 } } });
await ctx.addInitScript(demoInit);
await ctx.addInitScript(() => {
  window.addEventListener('DOMContentLoaded', () => {
    const c = document.createElement('div');
    c.id = '__cur';
    c.style.cssText = 'position:fixed;left:0;top:0;width:28px;height:28px;z-index:2147483647;pointer-events:none;transform:translate(-100px,-100px);transition:none;';
    c.innerHTML = '<svg viewBox="0 0 24 24" width="28" height="28"><path d="M4 2l15 9-6.5 1.6L9.5 19z" fill="#111" stroke="#fff" stroke-width="1.6" stroke-linejoin="round"/></svg>';
    document.documentElement.appendChild(c);
    window.addEventListener('mousemove', (e) => { c.style.transform = `translate(${e.clientX}px,${e.clientY}px)`; }, true);
  });
});
const page = await ctx.newPage();
await installDemoApi(page);
const t0 = Date.now();
const marks = {};
const mark = (n) => { marks[n] = +((Date.now() - t0) / 1000).toFixed(2); };
let mx = 960, my = 540;
const moveTo = async (loc, dx = 0, dy = 0) => {
  const b = await loc.boundingBox();
  const x = b.x + b.width / 2 + dx, y = b.y + b.height / 2 + dy;
  await page.mouse.move(x, y, { steps: 28 });
  mx = x; my = y;
};
await page.goto('http://localhost:3000/discover', { waitUntil: 'networkidle' });
await page.mouse.move(mx, my);
await page.waitForTimeout(1200);
mark('discover_empty');
// state filter
const state = page.getByText(/Select State/).first();
await moveTo(state); await page.waitForTimeout(250); await state.click();
await page.waitForTimeout(500);
await page.keyboard.type('Tamil', { delay: 140 });
await page.waitForTimeout(500);
const opt = page.getByText('Tamil Nadu', { exact: true }).first();
await moveTo(opt); await page.waitForTimeout(250); await opt.click();
mark('state_selected');
await page.waitForTimeout(900);
// industry
const ind = page.getByText('Manufacturing & Industrial', { exact: true }).first();
await moveTo(ind); await page.waitForTimeout(250); await ind.click();
mark('industry_selected');
await page.waitForTimeout(1600);
mark('results');
// hover through rows then open first
const first = page.getByText('Nilgiri Precision Components Pvt Ltd').first();
await moveTo(page.getByText('Vaigai Industrial Automation LLP').first(), 120, 0); await page.waitForTimeout(500);
await moveTo(first); await page.waitForTimeout(450);
mark('open_profile');
await first.click();
await page.waitForTimeout(1900);
mark('drawer');
const tab = page.getByText('Contact & Digital Channels').first();
await moveTo(tab); await page.waitForTimeout(300); await tab.click();
await page.waitForTimeout(1400);
mark('drawer_contacts');
await page.screenshot({path:'dbg2.png'});
const ul = page.getByRole('button', { name: /Unlock Lead/ }).first();
await moveTo(ul); await page.waitForTimeout(500);
mark('click_unlock');
await ul.click();
await page.waitForTimeout(1500);
await page.screenshot({path:'dbg3.png'});
mark('modal');
const conf = page.getByRole('button', { name: /Confirm & Unlock/ }).first();
await moveTo(conf); await page.waitForTimeout(500); mark('confirm'); await conf.click();
await page.waitForTimeout(2300);
await page.screenshot({path:'dbg4.png'});
mark('revealed');
await page.keyboard.press('Escape'); await page.waitForTimeout(700);
await page.goto('http://localhost:3000/discover/nilgiri-precision-components-pvt-ltd', { waitUntil: 'networkidle' });
await page.mouse.move(mx, my);
await page.waitForTimeout(1600);
mark('profile');
await page.mouse.wheel(0, 300); await page.waitForTimeout(900);
await page.mouse.wheel(0, -300); await page.waitForTimeout(600);
const people = page.getByText('People', { exact: true }).first();
await moveTo(people); await page.waitForTimeout(300); await people.click();
await page.waitForTimeout(2200);
await page.screenshot({path:'dbg5.png'});
mark('people');
mark('end');
const v = page.video();
await ctx.close();
console.log(JSON.stringify(marks), await v.path());
await browser.close();
